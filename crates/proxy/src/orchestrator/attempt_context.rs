use super::*;

#[allow(dead_code)]
pub(crate) struct AttemptExecutionContext<'a> {
    pub(crate) state: &'a ProxyAuthState,
    pub(crate) snapshot: &'a Arc<ConfigSnapshot>,
    pub(crate) candidate: &'a RouteCandidate,
    pub(crate) endpoint: EndpointKind,
    pub(crate) endpoint_str: &'static str,
    pub(crate) protocol: &'static str,
    pub(crate) is_messages: bool,
    pub(crate) is_admin: bool,
    pub(crate) request_id: RequestId,
    pub(crate) request_id_str: &'a str,
    pub(crate) now: i64,
    pub(crate) attempt_no: usize,
    pub(crate) attempt_started: i64,
    pub(crate) candidate_share_id: Option<String>,
    pub(crate) body: &'a Bytes,
    pub(crate) model: &'a SnapshotModel,
    pub(crate) caller: &'a ClientKeyRecord,
    pub(crate) reservation: Option<Reservation>,
    pub(crate) client_guard: &'a mut Option<MonthReservationGuard>,
    pub(crate) cap_guards: CandidateCapGuards,
    pub(crate) pin_ticket: Option<PinTicket>,
    pub(crate) resolved_session: Option<&'a ResolvedSession>,
    pub(crate) permit: &'a mut Option<OwnedSemaphorePermit>,
    pub(crate) input_only_estimate: i64,
    pub(crate) pin_key: Option<PinKey>,
    pub(crate) trace_thread_id: &'a str,
    pub(crate) trace_request: Option<&'a Bytes>,
    pub(crate) trace_retention_days: i64,
    pub(crate) store_flag: bool,
    pub(crate) pin_ttl_ms: i64,
    pub(crate) request_headers_json: Option<String>,
    /// Admission-decided geo attribution carrier (`#158`).
    pub(crate) metadata_json: Option<String>,
    pub(crate) origin: &'a OriginKey,
    pub(crate) secret: &'a str,
    pub(crate) input_tokens_est: i64,
    pub(crate) cand_cov_mode: &'a str,
    pub(crate) cand_mult_bps: i64,
    pub(crate) in_flight: &'a mut Option<InFlightGuard>,
    pub(crate) attempt_endpoint: EndpointKind,
    pub(crate) transcode_pair: Option<(
        llmroller_proto::transcode::WireProtocol,
        llmroller_proto::transcode::WireProtocol,
    )>,
    pub(crate) strip_injected_usage: bool,
    pub(crate) pinned_order: &'a mut Vec<RouteCandidate>,
    pub(crate) live_pin_ticket: &'a mut Option<PinTicket>,
    pub(crate) attempts: &'a mut Vec<UsageAttemptRecord>,
    pub(crate) try_outcomes: &'a mut Vec<TryOutcome>,
    pub(crate) last_retry_after_ms: &'a mut Option<i64>,
    pub(crate) failovers: &'a mut i64,
    pub(crate) pin_context: &'a PinFailureContext<'a>,
    pub(crate) tier_candidates: &'a [RouteCandidate],
}
