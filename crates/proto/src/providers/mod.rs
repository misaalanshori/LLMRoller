/// Look up a compiled-in provider preset by its `preset_id` slug (`F101`–`F180`).
#[must_use]
pub fn lookup_provider_preset(slug: &str) -> Option<&'static ProviderPresetSpec> {
    let normalized = slug.trim();
    ALL_PROVIDER_PRESET_SPECS
        .iter()
        .find(|spec| spec.preset_id.eq_ignore_ascii_case(normalized))
}
